namespace HalerithAddonClient.Core;

public static class ApiErrorTranslator
{
    private const string AuthenticationFailureMessage =
        "Minecraft authentication failed. Check your system time or sign in again.";

    /// <summary>
    /// Resolves a user-facing error message from a server response.
    /// Prefers the numeric <paramref name="code"/> when present; falls back to
    /// the legacy string <paramref name="errorCode"/> for internally-generated
    /// errors (network failures, JSON parse errors, etc.).
    /// </summary>
    public static string ToUserMessage(int? code, string? errorCode, string? fallbackMessage)
    {
        // ── Numeric codes sent by the server ────────────────────────────────
        if (code.HasValue)
        {
            return code.Value switch
            {
                1001 => "Your Minecraft username is not configured. Update the client settings and try again.",
                1002 => "Server not found. Check that the server ID is correct in the client settings.",
                1003 => "Your Minecraft username is not registered on this server. Please ask your server admin to add you.",
                1004 => "Your access to this server has been deactivated. Please contact your server admin.",
                1005 => "Required fields are missing. Review the client settings and try again.",
                1006 => "Minecraft account authorization failed. Ask the environment owner to grant access.",
                1007 => "Minecraft authentication expired. Sign in again.",
                1008 => "Minecraft account authorization failed. Ask the environment owner to review access.",
                1009 => "An unexpected authentication error occurred. Please try again later.",
                1010 => AuthenticationFailureMessage,
                1011 => "Invalid log file name.",
                1012 => "The server failed to store the log file.",
                1013 => "This Minecraft account has reached its client access limit.",
                _    => "The API request failed."
            };
        }

        // ── Legacy string codes (internally generated by ApiClient) ─────────
        return errorCode switch
        {
            "http_401"          => AuthenticationFailureMessage,
            "http_403"          => AuthenticationFailureMessage,
            "empty_response"    => "The server returned an empty response.",
            "invalid_json"      => "The server returned an unexpected response.",
            "json_parse_failed" => "Failed to parse the server response.",

            _ => string.IsNullOrWhiteSpace(fallbackMessage) ? "The API request failed." : fallbackMessage!.Trim()
        };
    }
}
